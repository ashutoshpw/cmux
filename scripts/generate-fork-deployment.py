#!/usr/bin/env python3
"""Validate the fork deployment contract and generate its build inputs."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import shlex
import sys
from urllib.parse import urlsplit


def load_configuration(repo: Path) -> dict[str, object]:
    config = json.loads((repo / "config/fork-deployment.json").read_text())
    if config.get("schemaVersion") != 1:
        raise ValueError("Unsupported fork deployment schemaVersion")
    if config.get("repository") != "ashutoshpw/cmux":
        raise ValueError("Deployment repository must be ashutoshpw/cmux")
    if config.get("productionOrigin") != "https://cmux.w3dev.app":
        raise ValueError("Production origin must be https://cmux.w3dev.app")
    for name in (
        "productionOrigin", "stagingOrigin", "artifactsOrigin", "presenceOrigin",
        "developmentPresenceOrigin", "irohV2Origin", "developmentIrohV2Origin",
    ):
        value = config.get(name)
        if not isinstance(value, str):
            raise ValueError(f"{name} must be an HTTPS origin")
        parsed = urlsplit(value)
        if (
            parsed.scheme != "https" or not parsed.hostname
            or parsed.username or parsed.password or parsed.port
            or parsed.path or parsed.query or parsed.fragment
            or not parsed.hostname.endswith(".w3dev.app")
        ):
            raise ValueError(f"{name} must be a bare, owned HTTPS origin")
    domain = config.get("publicationDomain")
    if not isinstance(domain, str) or not re.fullmatch(r"[a-z0-9.-]+\.w3dev\.app", domain):
        raise ValueError("publicationDomain must be an owned DNS zone")
    native = config.get("native")
    if not isinstance(native, dict):
        raise ValueError("native configuration is required")
    for name in ("macOSBundleID", "iOSBundleID"):
        if not re.fullmatch(r"app\.w3dev\.cmux(?:\.[a-zA-Z0-9-]+)*", str(native.get(name, ""))):
            raise ValueError(f"{name} must use the fork app identity")
    for name in ("macOSCallbackScheme", "iOSCallbackScheme", "macOSOAuthClientID", "iOSOAuthClientID", "webOAuthClientID"):
        if not re.fullmatch(r"cmux-w3dev(?:-[a-z0-9]+)*", str(native.get(name, ""))):
            raise ValueError(f"Invalid fork {name}")
    for name, expected in {
        "macOSBundleID": "app.w3dev.cmux",
        "iOSBundleID": "app.w3dev.cmux.ios",
        "macOSCallbackScheme": "cmux-w3dev",
        "iOSCallbackScheme": "cmux-w3dev-ios",
    }.items():
        if native.get(name) != expected:
            raise ValueError(f"{name} must use the agreed distinct fork identity {expected}")
    target = config.get("vercel")
    if not isinstance(target, dict):
        raise ValueError("Vercel configuration is required")
    if target.get("orgID") != "team_bhbVYR6BqVYMXKwAp7F1k5ib":
        raise ValueError("Unexpected Vercel team ID")
    if target.get("projectID") != "prj_3z4VuRVvSvlm5LYNnEuqHa4FKKtn":
        raise ValueError("Unexpected Vercel project ID")
    staging = target.get("stagingProjectID")
    if staging is not None and (
        not isinstance(staging, str) or not re.fullmatch(r"prj_[A-Za-z0-9]+", staging)
        or staging == target["projectID"]
    ):
        raise ValueError("Staging requires a separate explicit Vercel project ID")
    return config


def outputs(config: dict[str, object]) -> dict[str, str]:
    values = {name: value for name, value in config.items() if isinstance(value, str)}
    values.update(config["native"])
    swift = [
        "// Generated by scripts/generate-fork-deployment.py. Do not edit.",
        "/// Approved public deployment values for the cmux fork.",
        "public struct ForkDeployment: Sendable {",
    ]
    for name, value in values.items():
        swift += [f"    /// The configured {name} for this fork.", f"    public static let {name} = {json.dumps(value)}"]
    swift += ["}", ""]
    typescript = (
        "// Generated by scripts/generate-fork-deployment.py. Do not edit.\n"
        + "export const deployment = " + json.dumps(config, indent=2) + " as const;\n"
        + "export const forkDeployment = deployment;\n"
    )
    # Native names contain acronyms; expose stable, readable shell spellings.
    env = {"CMUX_FORK_" + re.sub(r"(?<!^)(?=[A-Z])", "_", name).upper(): value
           for name, value in values.items() if name not in config["native"]}
    for prefix, names in {
        "MACOS": ("macOSBundleID", "macOSCallbackScheme", "macOSOAuthClientID"),
        "IOS": ("iOSBundleID", "iOSCallbackScheme", "iOSOAuthClientID"),
        "WEB": (None, None, "webOAuthClientID"),
    }.items():
        for suffix, name in zip(("BUNDLE_ID", "CALLBACK_SCHEME", "OAUTH_CLIENT_ID"), names):
            if name:
                env[f"CMUX_FORK_{prefix}_{suffix}"] = values[name]
    env.update({"CMUX_FORK_VERCEL_ORG_ID": config["vercel"]["orgID"], "CMUX_FORK_VERCEL_PROJECT_ID": config["vercel"]["projectID"]})
    shell = "# Generated by scripts/generate-fork-deployment.py. Public values only.\n"
    shell += "\n".join(f"{name}={shlex.quote(value)}" for name, value in env.items()) + "\n"
    xcconfig = "// Generated by scripts/generate-fork-deployment.py. Do not edit.\n"
    for name, value in {
        "CMUX_API_BASE_URL": config["productionOrigin"],
        "CMUX_IROH_BROKER_BASE_URL": config["productionOrigin"],
        "CMUX_PRESENCE_BASE_URL": config["presenceOrigin"],
        "CMUX_IROH_V2_BASE_URL": config["irohV2Origin"],
    }.items():
        # The empty build-setting expansion prevents // becoming an xcconfig comment.
        xcconfig += f"{name} = {value.replace('https://', 'https:/$()/')}\n"
    return {
        "Packages/Shared/CMUXAuthCore/Sources/CMUXAuthCore/ForkDeployment.swift": "\n".join(swift),
        "web/services/deployment/config.ts": typescript,
        "workers/presence/src/generated/forkDeployment.ts": typescript,
        "workers/iroh-v2/src/generated/forkDeployment.ts": typescript,
        "agent-chat/fork-deployment.ts": typescript,
        "scripts/lib/fork-deployment.env": shell,
        "config/ForkDeployment.xcconfig": xcconfig,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        generated = outputs(load_configuration(args.repo))
    except (OSError, ValueError, TypeError, KeyError) as error:
        print(f"Invalid fork deployment configuration: {error}", file=sys.stderr)
        return 1
    drift = []
    for name, content in generated.items():
        path = args.repo / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                drift.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if drift:
        print("Fork deployment inputs are stale: " + ", ".join(drift), file=sys.stderr)
        return 1
    print(f"Fork deployment inputs {'verified' if args.check else 'generated'} ({len(generated)} files).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
